// lucide-react (installed version) has removed brand/logo icons entirely —
// no Instagram, no Twitter/X. These are hand-drawn to match its stroke
// conventions (24x24 viewBox, round caps, 2px stroke), the same exception
// already used for the sport chip icons lucide doesn't cover.

export function InstagramIcon({ size = 16, className = "" }: { size?: number; className?: string }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
    >
      <rect x="3" y="3" width="18" height="18" rx="5" />
      <circle cx="12" cy="12" r="4" />
      <circle cx="17.5" cy="6.5" r="1" fill="currentColor" stroke="none" />
    </svg>
  );
}

